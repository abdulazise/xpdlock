  // RS matrix multiplication
  static List<int> _rsMultiply(List<int> input) {
    if (input.length != 8) {
      throw ArgumentError('RS multiplication requires 8 bytes input');
    }

    final result = List<int>.filled(4, 0);
    
    // Menggunakan konstanta dari kelas
    final rsMatrix = _rsMatrixConst;

    // Perform matrix multiplication in GF(2^8)
    for (int i = 0; i < 4; i++) {
      int sum = 0;
      for (int j = 0; j < 8; j++) {
        if (rsMatrix[i][j] != 0 && input[j] != 0) {
          sum ^= _gfMultiply(rsMatrix[i][j], input[j]);
        }
      }
      result[i] = sum;
    }

    return result;
  }

  // Galois Field multiplication for RS matrix
  static int _gfMultiply(int a, int b) {
    int product = 0;
    int mask = 0x01;
    
    for (int i = 0; i < 8; i++) {
      if ((b & mask) != 0) {
        product ^= a;
      }
      
      bool highBitSet = (a & 0x80) != 0;
      a <<= 1;
      
      if (highBitSet) {
        a ^= 0x4D; // RS polynomial: x^8 + x^6 + x^3 + x^2 + 1
      }
      
      mask <<= 1;
    }
    
    return product & 0xFF;
  }

  // MDS matrix multiplication
  static List<int> _mdsMultiply(List<int> input) {
    if (input.length != 4) {
      throw ArgumentError('MDS multiplication requires 4 bytes input');
    }

    final result = List<int>.filled(4, 0);
    
    // Menggunakan konstanta dari kelas
    final mdsMatrix = _mdsMatrixConst;

    // Perform matrix multiplication in GF(2^8)
    for (int i = 0; i < 4; i++) {
      int sum = 0;
      for (int j = 0; j < 4; j++) {
        sum ^= _gfMultiplyMDS(mdsMatrix[i][j], input[j]);
      }
      result[i] = sum;
    }

    return result;
  }

  // Galois Field multiplication for MDS matrix
  static int _gfMultiplyMDS(int a, int b) {
    int result = 0;
    int mask = 0x01;
    
    // MDS uses different irreducible polynomial: x^8 + x^6 + x^5 + x^3 + 1
    // Renamed to follow Dart conventions (lowerCamelCase for constants)
    const int poly = 0x169; // 0x169 = x^8 + x^6 + x^5 + x^3 + 1
    
    for (int i = 0; i < 8; i++) {
      if ((b & mask) != 0) {
        result ^= a;
      }
      
      bool highBitSet = (a & 0x80) != 0;
      a <<= 1;
      
      if (highBitSet) {
        a ^= (poly & 0xFF);
      }
      
      mask <<= 1;
    }
    
    return result & 0xFF;
  }

