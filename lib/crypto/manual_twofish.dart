  // Single block encryption
  List<int> encryptBlock(List<int> block) {
    if (block.length != blockSize) {
      throw ArgumentError('Block size must be $blockSize bytes');
    }

    var state = List<int>.from(block);

    // Input whitening
    for (int i = 0; i < 4; i++) {
      state[i] ^= _roundKeys[0][i];
      state[i + 4] ^= _roundKeys[1][i];
    }

    // Main rounds
    for (int round = 0; round < rounds; round++) {
      // F function and round operations
      final t0 = _f(state.sublist(0, 4), round * 2);
      // Variabel t1 digunakan di bawah ini
      final t1 = _f(state.sublist(4, 8), round * 2 + 1);

      // Update state
      for (int i = 0; i < 4; i++) {
        final temp = state[i];
        state[i] = state[i + 4];
        state[i + 4] = temp ^ t0[i];
      }
    }

    // Output whitening
    for (int i = 0; i < 4; i++) {
      state[i] ^= _roundKeys[rounds * 2][i];
      state[i + 4] ^= _roundKeys[rounds * 2 + 1][i];
    }

    return state;
  }

  // Single block decryption
  List<int> decryptBlock(List<int> block) {
    if (block.length != blockSize) {
      throw ArgumentError('Block size must be $blockSize bytes');
    }

    var state = List<int>.from(block);

    // Reverse output whitening
    for (int i = 0; i < 4; i++) {
      state[i] ^= _roundKeys[rounds * 2][i];
      state[i + 4] ^= _roundKeys[rounds * 2 + 1][i];
    }

    // Main rounds in reverse
    for (int round = rounds - 1; round >= 0; round--) {
      final t0 = _f(state.sublist(0, 4), round * 2);
      // Variabel t1 digunakan di bawah ini
      final t1 = _f(state.sublist(4, 8), round * 2 + 1);

      // Update state
      for (int i = 0; i < 4; i++) {
        final temp = state[i];
        state[i] = state[i + 4] ^ t0[i];
        state[i + 4] = temp;
      }
    }

    // Reverse input whitening
    for (int i = 0; i < 4; i++) {
      state[i] ^= _roundKeys[0][i];
      state[i + 4] ^= _roundKeys[1][i];
    }

    return state;
  }

