  // Key schedule generation
  static List<List<int>> _generateRoundKeys(List<int> key) {
    final roundKeys = List.generate(rounds * 2, (_) => List<int>.filled(4, 0));
    final words = _keyToWords(key);

    for (int i = 0; i < rounds * 2; i++) {
      final A = _h(2 * i * 0x01010101, words, 0);
      final B = _rotateLeft(_h(2 * i + 1 * 0x01010101, words, 1), 8);
      
      roundKeys[i] = _wordToBytes(A + B);
    }

    return roundKeys;
  }

  // Generate S-box keys (removed unused return)
  static void _generateSBoxKeys(List<int> key) {
    final k = key.length ~/ 8;
    final sBoxKeys = List.generate(k, (_) => List<int>.filled(4, 0));

    for (int i = 0; i < k; i++) {
      final result = _rsMultiply(key.sublist(i * 8, (i + 1) * 8));
      sBoxKeys[k - 1 - i] = result;
    }
  }

  // h function for key schedule
  static int _h(int X, List<int> L, int k) {
    final List<int> y = List<int>.filled(4, 0);
    int z;

    // Break X into bytes
    y[0] = X & 0xFF;
    y[1] = (X >> 8) & 0xFF;
    y[2] = (X >> 16) & 0xFF;
    y[3] = (X >> 24) & 0xFF;

    // Apply key-dependent S-boxes
    switch (k) {
      case 4:
        y[0] = _q1[y[0]] ^ _getByte(L[3], 0);
        y[1] = _q0[y[1]] ^ _getByte(L[3], 1);
        y[2] = _q0[y[2]] ^ _getByte(L[3], 2);
        y[3] = _q1[y[3]] ^ _getByte(L[3], 3);
        // fall through
      case 3:
        y[0] = _q1[y[0]] ^ _getByte(L[2], 0);
        y[1] = _q1[y[1]] ^ _getByte(L[2], 1);
        y[2] = _q0[y[2]] ^ _getByte(L[2], 2);
        y[3] = _q0[y[3]] ^ _getByte(L[2], 3);
        // fall through
      case 2:
        y[0] = _q0[_q0[y[0]] ^ _getByte(L[1], 0)] ^ _getByte(L[0], 0);
        y[1] = _q0[_q1[y[1]] ^ _getByte(L[1], 1)] ^ _getByte(L[0], 1);
        y[2] = _q1[_q0[y[2]] ^ _getByte(L[1], 2)] ^ _getByte(L[0], 2);
        y[3] = _q1[_q1[y[3]] ^ _getByte(L[1], 3)] ^ _getByte(L[0], 3);
    }

    // MDS matrix multiplication
    z = _mdsMultiply(y)[0];
    z = (z << 8) | _mdsMultiply(y)[1];
    z = (z << 8) | _mdsMultiply(y)[2];
    z = (z << 8) | _mdsMultiply(y)[3];

    return z;
  }

